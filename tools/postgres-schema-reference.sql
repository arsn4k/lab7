CREATE COLLATION ci_hostname (LOCALE = 'und-u-ks-level2', PROVIDER = icu, DETERMINISTIC = False);

CREATE TABLE "Servers" (
    "Id" uuid NOT NULL,
    "Hostname" character varying(100) COLLATE ci_hostname NOT NULL,
    "IpAddress" character varying(45) NOT NULL,
    "Environment" character varying(30) NOT NULL,
    "CpuAlertThreshold" integer NOT NULL DEFAULT 90,
    "CurrentStatus" character varying(20) NOT NULL DEFAULT 'Maintenance',
    "LastHeartbeat" timestamp with time zone,
    "CreatedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_Servers" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_Servers_Hostname" CHECK (LENGTH("Hostname") BETWEEN 1 AND 100),
    CONSTRAINT "CK_Servers_CpuAlertThreshold" CHECK ("CpuAlertThreshold" BETWEEN 1 AND 100),
    CONSTRAINT "CK_Servers_Environment" CHECK ("Environment" IN ('Production', 'Staging', 'Development')),
    CONSTRAINT "CK_Servers_CurrentStatus" CHECK ("CurrentStatus" IN ('Healthy', 'Degraded', 'Down', 'Maintenance'))
);

CREATE TABLE "MetricSamples" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
    "ServerId" uuid NOT NULL,
    "CpuUsage" double precision NOT NULL,
    "MemoryUsage" double precision NOT NULL,
    "Temperature" numeric(5,2),
    "Humidity" numeric(5,2),
    "CollectedAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_MetricSamples" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_MetricSamples_CpuUsage" CHECK ("CpuUsage" BETWEEN 0 AND 100),
    CONSTRAINT "CK_MetricSamples_MemoryUsage" CHECK ("MemoryUsage" BETWEEN 0 AND 100),
    CONSTRAINT "CK_MetricSamples_Temperature" CHECK ("Temperature" BETWEEN -20 AND 120),
    CONSTRAINT "CK_MetricSamples_Humidity" CHECK ("Humidity" BETWEEN 0 AND 100),
    CONSTRAINT "FK_MetricSamples_Servers_ServerId" FOREIGN KEY ("ServerId")
        REFERENCES "Servers" ("Id") ON DELETE CASCADE
);

CREATE INDEX "IX_MetricSamples_ServerId_CollectedAt" ON "MetricSamples" ("ServerId", "CollectedAt");
CREATE UNIQUE INDEX "IX_Servers_Hostname" ON "Servers" ("Hostname");
